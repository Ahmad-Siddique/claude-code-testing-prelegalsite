"use client";

import { useState, useCallback } from "react";
import { DocumentTemplate, CoverPageSection, CoverPageField } from "@/lib/document-types";

interface DocumentEditorProps {
  template: DocumentTemplate;
}

export default function DocumentEditor({ template }: DocumentTemplate extends never ? never : DocumentEditorProps) {
  const [mode, setMode] = useState<"edit" | "preview">("edit");
  const [formData, setFormData] = useState<Record<string, string | boolean>>({});
  const [errors, setErrors] = useState<Record<string, string>>({});

  // Initialize form data with defaults
  const initFormData = useCallback(() => {
    const data: Record<string, string | boolean> = {};
    template.coverPageSections.forEach((section) => {
      section.fields.forEach((field) => {
        data[field.id] = field.defaultValue ?? "";
      });
    });
    setFormData(data);
  }, [template]);

  if (Object.keys(formData).length === 0) {
    initFormData();
  }

  const updateField = (fieldId: string, value: string | boolean) => {
    const newData = { ...formData, [fieldId]: value };
    setFormData(newData);
    setErrors({});
  };

  const getFieldValue = (fieldId: string): string | boolean => {
    return formData[fieldId] ?? "";
  };

  const isFieldVisible = (field: CoverPageField): boolean => {
    if (!field.dependsOn) return true;
    const parentValue = getFieldValue(field.dependsOn.fieldId);
    return String(parentValue) === field.dependsOn.value;
  };

  const renderStandardTerms = (): string => {
    let content = template.standardTerms;
    template.coverPageSections.forEach((section) => {
      section.fields.forEach((field) => {
        const value = getFieldValue(field.id);
        const placeholder = `{{${field.label}}}`;
        content = content.split(placeholder).join(String(value));
      });
    });
    return content;
  };

  const handleSave = () => {
    const newErrors: Record<string, string> = {};
    template.coverPageSections.forEach((section) => {
      section.fields.forEach((field) => {
        if (field.required && isFieldVisible(field)) {
          const value = getFieldValue(field.id);
          if (!value || (typeof value === "string" && value.trim() === "")) {
            newErrors[field.id] = `${field.label} is required`;
          }
        }
      });
    });
    setErrors(newErrors);
    if (Object.keys(newErrors).length === 0) {
      alert("Document saved successfully!");
    }
  };

  const handleExport = () => {
    const docContent = `# ${template.name}

## Cover Page

${template.coverPageSections
  .map((section) => {
    return `### ${section.title}

${section.fields
  .filter((f) => isFieldVisible(f))
  .map((f) => `- **${f.label}:** ${getFieldValue(f.id)}`)
  .join("\n")}
`;
  })
  .join("\n")}

## Standard Terms

${renderStandardTerms()}

---

Generated by Donner Law Firm — Prelegal Document Editor
Template: ${template.name} v${template.version}
License: ${template.license}
`;

    const blob = new Blob([docContent], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${template.name.replace(/\s+/g, "-").toLowerCase()}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="min-h-screen bg-prelegal-50 dark:bg-prelegal-900">
      {/* Header */}
      <header className="bg-white dark:bg-prelegal-900 border-b border-prelegal-100 dark:border-prelegal-800 sticky top-0 z-40">
        <div className="max-w-7xl mx-auto px-4">
          <div className="flex items-center justify-between h-16 md:h-20">
            <div className="flex items-center gap-3">
              <div className="h-10 w-10 rounded-xl bg-prelegal-500 flex items-center justify-center">
                <svg className="w-6 h-6 text-white" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                  <path d="M14 2H6a2 2 0 00-2 2v16a2 2 0 002 2h12a2 2 0 002-2V8z" />
                  <polyline points="14 2 14 8 20 8" />
                  <line x1="9" y1="13" x2="15" y2="13" />
                  <line x1="9" y1="17" x2="13" y2="17" />
                </svg>
              </div>
              <div>
                <h1 className="text-xl font-bold text-prelegal-900 dark:text-white">{template.name}</h1>
                <p className="text-sm text-prelegal-500 dark:text-prelegal-400">
                  v{template.version} • {template.description}
                </p>
              </div>
            </div>
            <div className="flex items-center gap-4">
              <button
                onClick={() => setMode("edit")}
                className={`px-4 py-2 rounded-lg text-sm font-medium transition-all ${
                  mode === "edit"
                    ? "bg-prelegal-500 text-white shadow-md"
                    : "bg-prelegal-100 dark:bg-prelegal-800 text-prelegal-600 dark:text-prelegal-300 hover:bg-prelegal-200 dark:hover:bg-prelegal-700"
                }`}
              >
                Edit Mode
              </button>
              <button
                onClick={() => setMode("preview")}
                className={`px-4 py-2 rounded-lg text-sm font-medium transition-all ${
                  mode === "preview"
                    ? "bg-prelegal-500 text-white shadow-md"
                    : "bg-prelegal-100 dark:bg-prelegal-800 text-prelegal-600 dark:text-prelegal-300 hover:bg-prelegal-200 dark:hover:bg-prelegal-700"
                }`}
              >
                Preview Mode
              </button>
              <button
                onClick={handleExport}
                className="bg-prelegal-800 dark:bg-prelegal-700 text-white px-5 py-2 rounded-lg text-sm font-medium hover:bg-prelegal-700 dark:hover:bg-prelegal-600 transition-colors"
              >
                Export Markdown
              </button>
            </div>
          </div>
        </div>
      </header>

      <div className="max-w-7xl mx-auto px-4 py-8">
        {mode === "edit" ? (
          <div className="grid lg:grid-cols-1 xl:grid-cols-3 gap-8">
            {/* Cover Page Form */}
            <div className="xl:col-span-2 space-y-8">
              {template.coverPageSections.map((section) => (
                <section
                  key={section.id}
                  className="bg-white dark:bg-prelegal-900 rounded-2xl p-8 shadow-sm border border-prelegal-100 dark:border-prelegal-800"
                >
                  <div className="flex items-center gap-3 mb-6">
                    <div className="h-8 w-8 rounded-lg bg-prelegal-500 flex items-center justify-center text-white font-medium">
                      {section.title.charAt(0).toUpperCase()}
                    </div>
                    <div>
                      <h2 className="text-lg font-bold text-prelegal-900 dark:text-white">
                        {section.title}
                      </h2>
                      {section.description && (
                        <p className="text-prelegal-500 dark:text-prelegal-400 text-sm">{section.description}</p>
                      )}
                    </div>
                  </div>
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                    {section.fields.map((field) => {
                      const visible = isFieldVisible(field);
                      const error = errors[field.id];
                      return (
                        <div
                          key={field.id}
                          className={`${visible ? "" : "hidden"} space-y-2`}
                        >
                          <label className="block text-sm font-medium text-prelegal-700 dark:text-prelegal-300">
                            {field.label} {field.required && <span className="text-prelegal-500">*</span>}
                          </label>
                          {field.type === "textarea" ? (
                            <textarea
                              value={String(getFieldValue(field.id))}
                              onChange={(e) => updateField(field.id, e.target.value)}
                              rows={4}
                              placeholder={field.placeholder}
                              className={`w-full px-4 py-3 rounded-xl border transition-colors focus:outline-none focus:ring-2 focus:ring-prelegal-500 focus:border-transparent ${error ? "border-prelegal-500" : "border-prelegal-200 dark:border-prelegal-700 bg-prelegal-50 dark:bg-prelegal-800"}`}
                            />
                          ) : field.type === "checkbox" ? (
                            <div className="flex items-center gap-3">
                              <input
                                type="checkbox"
                                checked={Boolean(getFieldValue(field.id))}
                                onChange={(e) => updateField(field.id, e.target.checked)}
                                className="w-5 h-5 rounded border-prelegal-500 text-prelegal-500 focus:ring-prelegal-500"
                              />
                              <span className="text-prelegal-700 dark:text-prelegal-300 text-sm">{field.placeholder || field.label}</span>
                            </div>
                          ) : field.type === "radio" ? (
                            <div className="space-y-2">
                              {field.options!.map((option) => (
                                <label
                                  key={option}
                                  className="flex items-center gap-2 cursor-pointer text-sm text-prelegal-700 dark:text-prelegal-300"
                                >
                                  <input
                                    type="radio"
                                    name={field.id}
                                    checked={String(getFieldValue(field.id)) === option}
                                    onChange={() => updateField(field.id, option)}
                                    className="w-4 h-4 rounded border-prelegal-500 text-prelegal-500 focus:ring-prelegal-500"
                                  />
                                  {option}
                                </label>
                              ))}
                            </div>
                          ) : field.type === "select" ? (
                            <select
                              value={String(getFieldValue(field.id))}
                              onChange={(e) => updateField(field.id, e.target.value)}
                              className={`w-full px-4 py-3 rounded-xl border transition-colors focus:outline-none focus:ring-2 focus:ring-prelegal-500 focus:border-transparent ${error ? "border-prelegal-500" : "border-prelegal-200 dark:border-prelegal-700 bg-prelegal-50 dark:bg-prelegal-800"}`}
                            >
                              {field.options!.map((option) => (
                                <option key={option} value={option}>{option}</option>
                              ))}
                            </select>
                          ) : field.type === "date" ? (
                            <input
                              type="date"
                              value={String(getFieldValue(field.id))}
                              onChange={(e) => updateField(field.id, e.target.value)}
                              className={`w-full px-4 py-3 rounded-xl border transition-colors focus:outline-none focus:ring-2 focus:ring-prelegal-500 focus:border-transparent ${error ? "border-prelegal-500" : "border-prelegal-200 dark:border-prelegal-700 bg-prelegal-50 dark:bg-prelegal-800"}`}
                            />
                          ) : field.type === "email" ? (
                            <input
                              type="email"
                              value={String(getFieldValue(field.id))}
                              onChange={(e) => updateField(field.id, e.target.value)}
                              placeholder={field.placeholder}
                              className={`w-full px-4 py-3 rounded-xl border transition-colors focus:outline-none focus:ring-2 focus:ring-prelegal-500 focus:border-transparent ${error ? "border-prelegal-500" : "border-prelegal-200 dark:border-prelegal-700 bg-prelegal-50 dark:bg-prelegal-800"}`}
                            />
                          ) : (
                            <input
                              type="text"
                              value={String(getFieldValue(field.id))}
                              onChange={(e) => updateField(field.id, e.target.value)}
                              placeholder={field.placeholder}
                              className={`w-full px-4 py-3 rounded-xl border transition-colors focus:outline-none focus:ring-2 focus:ring-prelegal-500 focus:border-transparent ${error ? "border-prelegal-500" : "border-prelegal-200 dark:border-prelegal-700 bg-prelegal-50 dark:bg-prelegal-800"}`}
                            />
                          )}
                          {error && <p className="text-prelegal-500 text-xs">{error}</p>}
                          {field.helpText && (
                            <p className="text-prelegal-400 dark:text-prelegal-500 text-xs mt-1">{field.helpText}</p>
                          )}
                        </div>
                      );
                    })}
                  </div>
                </section>
              ))}
            </div>

            {/* Preview Sidebar */}
            <aside className="space-y-6">
              <div className="bg-white dark:bg-prelegal-900 rounded-2xl p-8 shadow-sm border border-prelegal-100 dark:border-prelegal-800 sticky top-24">
                <h3 className="text-lg font-bold text-prelegal-900 dark:text-white mb-6">Live Preview</h3>
                <div className="bg-prelegal-50 dark:bg-prelegal-800 rounded-xl p-4 max-h-[600px] overflow-y-auto text-prelegal-600 dark:text-prelegal-300 text-sm leading-relaxed border border-prelegal-100 dark:border-prelegal-700">
                  {template.coverPageSections.map((section) => (
                    <div key={section.id} className="mb-4">
                      <h4 className="font-medium text-prelegal-900 dark:text-white mb-2">{section.title}</h4>
                      {section.fields
                        .filter((f) => isFieldVisible(f))
                        .map((f) => (
                          <p key={f.id} className="mb-1">
                            <span className="font-medium">{f.label}:</span>{" "}
                            {String(getFieldValue(f.id)) || (
                              <span className="italic text-prelegal-400 dark:text-prelegal-600">— {f.placeholder || "Not set"} —</span>
                            )}
                          </p>
                        ))}
                    </div>
                  ))}
                </div>
              </div>

              <div className="bg-white dark:bg-prelegal-900 rounded-2xl p-6 shadow-sm border border-prelegal-100 dark:border-prelegal-800">
                <h3 className="font-bold text-prelegal-900 dark:text-white mb-3">Template Info</h3>
                <div className="space-y-3 text-sm text-prelegal-600 dark:text-prelegal-400">
                  <p><span className="font-medium">Version:</span> {template.version}</p>
                  <p><span className="font-medium">License:</span> {template.license}</p>
                  <p><span className="font-medium">Source:</span> Common Paper</p>
                  <p className="text-xs text-prelegal-400 italic">
                    Free to use and modify under {template.license}
                  </p>
                </div>
              </div>
            </aside>
          </div>
        ) : (
          <article className="prose prose-sm dark:prose-invert max-w-none bg-white dark:bg-prelegal-900 rounded-2xl p-8 shadow-sm border border-prelegal-100 dark:border-prelegal-800 max-h-[85vh] overflow-y-auto">
            <h1 className="text-3xl font-bold mb-2">{template.name}</h1>
            <p className="text-prelegal-600 dark:text-prelegal-400 mb-6">{template.description}</p>

            <hr className="border-prelegal-100 dark:border-prelegal-800 my-6" />

            {/* Cover Page */}
            <section className="mb-8">
              <h2 className="text-2xl font-bold mb-4">Cover Page</h2>
              {template.coverPageSections.map((section) => (
                <div key={section.id} className="mb-6">
                  <h3 className="text-xl font-semibold mb-2">{section.title}</h3>
                  <ul className="list-disc list-inside space-y-2 text-prelegal-600 dark:text-prelegal-300">
                    {section.fields
                      .filter((f) => isFieldVisible(f))
                      .map((f) => (
                        <li key={f.id}>
                          <span className="font-medium">{f.label}:</span>{" "}
                          {String(getFieldValue(f.id)) || (
                            <span className="italic text-prelegal-400 dark:text-prelegal-600">({f.placeholder || "Not specified"})</span>
                          )}
                        </li>
                      ))}
                  </ul>
                </div>
              ))}
            </section>

            <hr className="border-prelegal-100 dark:border-prelegal-800 my-6" />

            {/* Standard Terms */}
            <section>
              <h2 className="text-2xl font-bold mb-4">Standard Terms</h2>
              <div
                className="text-prelegal-600 dark:text-prelegal-300 leading-relaxed text-sm"
                dangerouslySetInnerHTML={{ __html: markdownToHtml(renderStandardTerms()) }}
              />
            </section>
          </article>
        )}
      </div>

      {/* Action Buttons (sticky bottom in edit mode)} */}
      {mode === "edit" && (
        <div className="fixed bottom-0 left-0 right-0 bg-white dark:bg-prelegal-900 border-t border-prelegal-100 dark:border-prelegal-800 p-4 md:p-8 shadow-lg z-30">
          <div className="max-w-7xl mx-auto">
            <div className="flex justify-end gap-4">
              <button
                onClick={handleSave}
                className="px-6 py-3 bg-prelegal-600 text-white rounded-xl font-medium hover:bg-prelegal-700 transition-colors flex items-center gap-2"
              >
                <svg className="w-5 h-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                  <path d="M19 21H5a2 2 0 01-2-2V5a2 2 0 012-2h11l5 5v11a2 2 0 01-2 2z" />
                  <polyline points="17 21 17 13 7 13 7 21" />
                  <polyline points="7 3 7 8 15 8" />
                </svg>
                Save Document
              </button>
              <button
                onClick={handleExport}
                className="px-6 py-3 bg-prelegal-500 text-white rounded-xl font-medium hover:bg-prelegal-600 transition-colors flex items-center gap-2"
              >
                <svg className="w-5 h-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                  <path d="M21 15v4a2 2 0 01-2 2H5a2 2 0 01-2-2v-4" />
                  <polyline points="7 10 12 15 17 10" />
                  <line x1="12" y1="15" x2="12" y2="3" />
                </svg>
                Export Document
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

function markdownToHtml(markdown: string): string {
  return markdown
    .replace(/^# (.*$)/gim, "<h1>$1</h1>")
    .replace(/^## (.*$)/gim, "<h2>$1</h2>")
    .replace(/^### (.*$)/gim, "<h3>$1</h3>")
    .replace(/\*\*(.*?)\*\*/gim, "<strong>$1</strong>")
    .replace(/\*(.*?)\*/gim, "<em>$1</em>")
    .replace(/\n/g, "<br/>");
}